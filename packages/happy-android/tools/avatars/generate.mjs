#!/usr/bin/env node
// Copies happy-ios's avatar placeholders into this app, so an ID wears the
// same picture and the same live shader on both phones:
//
// - the 200 WebP pictures, their provenance notice and the shaders' MIT
//   license, into app/src/main/assets/avatar-placeholders;
// - happy-ios's AvatarShaderTable.swift (made by its
//   scripts/generate-avatar-shader-table.mjs from @craftedstudios/shaders'
//   own code) as AvatarShaderTable.kt, number for number.
//
// Run after happy-ios regenerates either:
//
//   node tools/avatars/generate.mjs
//
// AvatarShaderTest and AvatarPlaceholderTest fail until the copies match.
import { copyFileSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const android = join(dirname(fileURLToPath(import.meta.url)), '../..');
const ios = join(android, '../happy-ios');
const pictures = join(ios, 'Sources/HappyUI/Resources/AvatarPlaceholders');
const assets = join(android, 'app/src/main/assets/avatar-placeholders');

rmSync(assets, { recursive: true, force: true });
mkdirSync(assets, { recursive: true });
const files = readdirSync(pictures).filter((name) => /^avatar-placeholder-\d{3}\.webp$|\.md$|\.txt$/.test(name));
for (const name of files) copyFileSync(join(pictures, name), join(assets, name));

const swift = readFileSync(join(ios, 'Sources/HappyLayout/AvatarShaderTable.swift'), 'utf8');
const version = swift.match(/@craftedstudios\/shaders (\S+)/)[1];
const effects = { linear: 0, thermal: 1, topography: 2, plasma: 3, radial: 4 };
const rows = [...swift.matchAll(/\.init\(effect: \.(\w+), colors: \[(.*?)\], layout: SIMD4\((.*?)\), angle: (\S+), phase: (\S+)\),/g)].map(
  ([, effect, colors, layout, angle, phase]) => {
    const rgb = [...colors.matchAll(/SIMD3\((.*?)\)/g)].flatMap(([, c]) => c.split(', '));
    if (rgb.length !== 12) throw new Error(`${effect}: ${rgb.length / 3} colours`);
    const values = [effects[effect], ...rgb, ...layout.split(', '), angle, phase];
    return `    ${values.map((v) => `${v}f`).join(', ')},`;
  },
);
if (rows.length !== 200) throw new Error(`${rows.length} rows, not 200`);

writeFileSync(join(android, 'app/src/main/kotlin/com/slopus/happy/ui/components/avatar/AvatarShaderTable.kt'), `// Generated by tools/avatars/generate.mjs from happy-ios's AvatarShaderTable.swift,
// itself made from @craftedstudios/shaders ${version} (MIT, Copyright (c) 2026 Crafted Studios).
// Do not edit.
package com.slopus.happy.ui.components.avatar

/**
 * Each placeholder's drawing, in the pictures' order, [AvatarShader.ROW]
 * floats each: the effect, the four colours (sRGB 0...1), the layout (x, y,
 * turn, zoom), the angle and the phase.
 */
internal val avatarShaderTable = floatArrayOf(
${rows.join('\n')}
)
`);
console.log(`${files.length} files into ${assets}; ${rows.length} shader rows from @craftedstudios/shaders ${version}`);
