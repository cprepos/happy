#!/usr/bin/env bash
# Create the live-browser stack's data and secrets under $HAPPY_BROWSER_HOME
# (default ~/.local/share/happy-browser). Idempotent: an existing secret is
# never replaced, only missing ones are generated. Secrets are never printed.
#
#   secrets/browser.env   compose --env-file: every secret below, KEY=value
#   secrets/happy-agent.env  AUTO_BROWSER_TOKEN=..., for the happy-agent container
#   secrets/api-token     auto-browser controller bearer token (MCP + REST)
#   secrets/vnc-password  noVNC password (VNC uses the first 8 characters)
#   secrets/bridge-token  bearer token the bridge's MCP client uses on /api/*
#   data/                 auto-browser controller /data (profile, artifacts, audit)
#   bridge/               bridge link store
#
# Then, from a one-shot container (scripts/browser-perms.sh), every directory gets the owner its
# service's own uid needs, and the bridge's and launcher's secret files are copied into
# secrets-bridge/ and secrets-launcher/, owned by those uids, 0400. secrets/ stays the operator's.
set -euo pipefail

ROOT="${HAPPY_BROWSER_HOME:-$HOME/.local/share/happy-browser}"
SECRETS="$ROOT/secrets"
umask 077

mkdir -p "$ROOT" "$SECRETS"
chmod 700 "$ROOT" "$SECRETS"
# data/pods/slot-N (one per running pod) and data/chats/<hash>/auth (a chat's saved logins)
# are made by the pod launcher; run/ holds its socket, which only the bridge mounts. The service
# directories (data/, bridge/, run/ and the rest) are made, and owned, by browser-perms.sh below.

rand_hex() { openssl rand -hex "$1"; }
# Eight characters: VNC authentication ignores anything past the eighth.
rand_vnc() { local s; s=$(openssl rand -base64 48 | tr -dc 'A-Za-z0-9'); printf '%s' "${s:0:8}"; }
# A Fernet key: url-safe base64 of 32 random bytes.
rand_fernet() { openssl rand 32 | base64 | tr '+/' '-_'; }

made=()
ensure_file() { # name generator...
  local f="$SECRETS/$1"; shift
  if [[ ! -s "$f" ]]; then
    "$@" >"$f.tmp" && mv "$f.tmp" "$f"
    made+=("$(basename "$f")")
  fi
  chmod 600 "$f"
}

ensure_file api-token rand_hex 32
ensure_file vnc-password rand_vnc
ensure_file bridge-token rand_hex 32
ensure_file auth-state-key rand_fernet
ensure_file share-token-secret rand_hex 32

# browser.env is rebuilt from the files above on every run, so it always
# matches them; it holds nothing that is not already in those files.
tmp="$SECRETS/browser.env.tmp"
{
  echo "# Generated by make browser-init from the files beside it. Do not edit; edit those."
  printf 'API_BEARER_TOKEN=%s\n' "$(cat "$SECRETS/api-token")"
  printf 'VNC_PASSWORD=%s\n' "$(cat "$SECRETS/vnc-password")"
  printf 'AUTH_STATE_ENCRYPTION_KEY=%s\n' "$(cat "$SECRETS/auth-state-key")"
  printf 'SHARE_TOKEN_SECRET=%s\n' "$(cat "$SECRETS/share-token-secret")"
} >"$tmp"
mv "$tmp" "$SECRETS/browser.env"
chmod 600 "$SECRETS/browser.env"

# --env-file for the happy-agent container, whose mcp.toml names this variable
# in bearer_token_env_var (README: Happy Agent).
tmp="$SECRETS/happy-agent.env.tmp"
printf 'AUTO_BROWSER_TOKEN=%s\n' "$(cat "$SECRETS/api-token")" >"$tmp"
mv "$tmp" "$SECRETS/happy-agent.env"
chmod 600 "$SECRETS/happy-agent.env"

# Owners and the services' secret copies (compose.browser.yml names the uids). Root in a container
# with only CHOWN, DAC_OVERRIDE and FOWNER, no network: HAPPY_BROWSER_HOME is the operator's own
# tree, so this hands parts of it to the services' uids and nothing else.
HERE="$(cd "$(dirname "$0")" && pwd)"
PERMS_IMAGE="node:22-alpine@sha256:fe4f6d74e20370acb04ad889077d14d0f64a9c8ea6a42bc60cddf1e844699914"
docker run --rm --network none --read-only --security-opt no-new-privileges:true -u 0:0 \
  --cap-drop ALL --cap-add CHOWN --cap-add DAC_OVERRIDE --cap-add FOWNER \
  -e CONTROLLER_UID="${CONTROLLER_UID:-1993}" -e BROWSER_NODE_UID="${BROWSER_NODE_UID:-1994}" \
  -e BRIDGE_UID="${BRIDGE_UID:-1992}" -e DOCKER_PROXY_UID="${DOCKER_PROXY_UID:-1995}" \
  -e LAUNCHER_SOCKET_GID="${LAUNCHER_SOCKET_GID:-1996}" \
  -v "$ROOT:/h" -v "$HERE/browser-perms.sh:/browser-perms.sh:ro" --entrypoint sh "$PERMS_IMAGE" /browser-perms.sh

if ((${#made[@]})); then
  echo "browser-init: generated ${made[*]} in $SECRETS (mode 600)"
else
  echo "browser-init: all secrets already present in $SECRETS"
fi
